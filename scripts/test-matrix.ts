import { existsSync, readFileSync } from "node:fs";

/**
 * Generates docs/quality/test-matrix.md from the coverage and mutation reports.
 * Run `bun run test:coverage` and `bun run test:mutation` first.
 */
const COVERAGE = "coverage/lcov.info";
const MUTATION = "reports/mutation/mutation.json";
const OUTPUT = "docs/quality/test-matrix.md";

type Coverage = { lines: number | null; functions: number | null };
type Mutant = {
  status: string;
  mutatorName: string;
  replacement: string;
  location: { start: { line: number } };
};
type FileReport = { mutants: Mutant[] };
type MutationReport = { files: Record<string, FileReport> };

const TEST_OVERRIDES: Record<string, string[]> = {
  "server/config.ts": ["server/db.test.ts"],
  "server/keys.ts": ["server/static.test.ts"],
  "src/lib/app/auth.ts": ["src/lib/app/controller.test.ts"],
  "src/lib/app/context.ts": ["tests/e2e/*"],
  "src/lib/app/copy.ts": ["tests/e2e/*", "src/lib/components/AccountPanel.svelte"],
  "src/lib/app/types.ts": ["src/lib/app/controller.test.ts"],
  "src/lib/ui/component-test.ts": ["src/lib/ui/*.svelte.test.ts"],
};

function percent(hit: number, total: number): number | null {
  return total > 0 ? Math.round((hit / total) * 10_000) / 100 : null;
}

function readCoverage(): Map<string, Coverage> {
  const result = new Map<string, Coverage>();
  const lcov = existsSync(COVERAGE) ? readFileSync(COVERAGE, "utf8") : "";
  const records = lcov.split("end_of_record");

  for (const record of records) {
    const source = /^SF:(.+)$/m.exec(record)?.[1];
    if (!source) {
      continue;
    }
    const lf = Number(/^LF:(\d+)$/m.exec(record)?.[1] ?? 0);
    const lh = Number(/^LH:(\d+)$/m.exec(record)?.[1] ?? 0);
    const fnf = Number(/^FNF:(\d+)$/m.exec(record)?.[1] ?? 0);
    const fnh = Number(/^FNH:(\d+)$/m.exec(record)?.[1] ?? 0);
    result.set(source.replace(/^\.\//, ""), {
      lines: percent(lh, lf),
      functions: percent(fnh, fnf),
    });
  }

  return result;
}

function readMutation(): MutationReport {
  if (!existsSync(MUTATION)) {
    throw new Error(`${MUTATION} is missing; run bun run test:mutation first`);
  }
  return JSON.parse(readFileSync(MUTATION, "utf8")) as MutationReport;
}

function testsFor(file: string): string {
  const override = TEST_OVERRIDES[file];
  if (override) {
    return override.join("; ");
  }
  const sameName = file.replace(/\.ts$/, ".test.ts");
  return existsSync(sameName) ? sameName : "indirect";
}

function fmt(value: number | null): string {
  return value === null ? "–" : `${value.toFixed(2)}%`;
}

const coverage = readCoverage();
const mutation = readMutation();
const rows: {
  file: string;
  tests: string;
  lines: number | null;
  functions: number | null;
  killed: number;
  timeout: number;
  survived: number;
  total: number;
  score: number;
}[] = [];
const survivors: { file: string; line: number; mutator: string; replacement: string }[] = [];

for (const [file, report] of Object.entries(mutation.files)) {
  const mutants = report.mutants ?? [];
  const killed = mutants.filter((m) => m.status === "Killed").length;
  const timeout = mutants.filter((m) => m.status === "Timeout").length;
  const survived = mutants.filter((m) => m.status === "Survived").length;
  const total = mutants.length;
  const score = total > 0 ? Math.round(((killed + timeout) / total) * 10_000) / 100 : 0;
  const cov = coverage.get(file);
  rows.push({
    file,
    tests: testsFor(file),
    lines: cov?.lines ?? null,
    functions: cov?.functions ?? null,
    killed,
    timeout,
    survived,
    total,
    score,
  });

  for (const mutant of mutants.filter((m) => m.status === "Survived").slice(0, 3)) {
    survivors.push({
      file,
      line: mutant.location?.start?.line ?? 0,
      mutator: mutant.mutatorName,
      replacement: mutant.replacement,
    });
  }
}

rows.sort((a, b) => a.file.localeCompare(b.file));
const total = rows.reduce(
  (acc, row) => ({
    killed: acc.killed + row.killed,
    timeout: acc.timeout + row.timeout,
    survived: acc.survived + row.survived,
    total: acc.total + row.total,
  }),
  { killed: 0, timeout: 0, survived: 0, total: 0 },
);
const totalScore = Math.round(((total.killed + total.timeout) / total.total) * 10_000) / 100;
const date = new Date().toISOString().slice(0, 10);

const lines: string[] = [
  "# Test matrix",
  "",
  `> Generated by \`bun run matrix\` on ${date}. Do not edit by hand.`,
  "",
  "Sources: `bun run test:coverage` (`coverage/lcov.info`) and `bun run test:mutation`",
  "(`reports/mutation/mutation.json`). Timed-out mutants count as killed. Lines/Functions are",
  "coverage percentages; K/T/S are killed, timed out and survived mutants.",
  "",
  'Stryker runs with `coverageAnalysis: "off"`, so it cannot reliably say which test *covered*',
  "a mutant. The JSON report does include `killedBy` test names, but this matrix attributes tests",
  "to modules by convention (`X.test.ts`) plus a small override map for shared helpers.",
  "",
  `**Total:** ${fmt(totalScore)} mutation score · ${total.killed} killed · ${total.timeout} timed out · ${total.survived} survived · ${total.total} mutants`,
  "",
  "| Module | Test file(s) | Lines | Functions | K / T / S | Mutants | Score |",
  "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
];

for (const row of rows) {
  lines.push(
    `| \`${row.file}\` | ${row.tests} | ${fmt(row.lines)} | ${fmt(row.functions)} | ${row.killed} / ${row.timeout} / ${row.survived} | ${row.total} | ${fmt(row.score)} |`,
  );
}

lines.push("", "## Follow-ups", "");
const focus = [...rows].sort((a, b) => b.survived - a.survived).slice(0, 6);
for (const row of focus) {
  lines.push(
    `- \`${row.file}\`: ${row.survived} survivors, score ${fmt(row.score)} — add assertions for the surviving branches in ${row.tests}.`,
  );
}

lines.push("", "### Sample surviving mutants", "");
for (const mutant of survivors.slice(0, 10)) {
  lines.push(`- \`${mutant.file}:${mutant.line}\` — ${mutant.mutator} → \`${mutant.replacement}\``);
}

await Bun.write(OUTPUT, `${lines.join("\n")}\n`);
console.info(`Wrote ${OUTPUT}: ${rows.length} modules, ${fmt(totalScore)} mutation score`);
